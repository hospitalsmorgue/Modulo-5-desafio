-- ---------------------------------------------------------------------------
-- Bônus: relatório de engajamento por curso
-- Total de matriculados, média de idade (anos completos) e matrículas dos últimos 30 dias.
-- Cursos sem aluno continuam na lista por causa do LEFT JOIN.
-- ---------------------------------------------------------------------------

SELECT c.id,
       c.nome AS curso,
       COUNT(m.id) AS total_matriculados,
       ROUND(AVG(EXTRACT(YEAR FROM AGE(CURRENT_DATE, a.data_nascimento)))::numeric, 1) AS media_idade,
       COUNT(m.id) FILTER (
           WHERE m.data_matricula >= CURRENT_DATE - INTERVAL '30 days'
       ) AS matriculados_ultimos_30_dias
FROM curso c
LEFT JOIN matricula m ON m.curso_id = c.id
LEFT JOIN aluno a ON a.id = m.aluno_id
GROUP BY c.id, c.nome
ORDER BY c.nome, c.id;
