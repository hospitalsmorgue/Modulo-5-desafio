-- Listar alunos
-- JPQL: SELECT a FROM Aluno a ORDER BY a.nome, a.id
SELECT id, nome, email, data_nascimento
FROM aluno
ORDER BY nome, id;

-- Buscar aluno por e-mail (sem diferenciar maiúsculas)
-- JPQL: SELECT a FROM Aluno a WHERE LOWER(a.email) = :email
SELECT id, nome, email, data_nascimento
FROM aluno
WHERE LOWER(email) = LOWER('ana.silva@email.com');

-- Listar cursos
-- JPQL: SELECT c FROM Curso c ORDER BY c.nome, c.id
SELECT id, nome, descricao, carga_horaria
FROM curso
ORDER BY nome, id;

-- Buscar curso pelo nome ou por parte dele
-- JPQL: SELECT c FROM Curso c WHERE LOWER(c.nome) LIKE :termo ORDER BY c.nome, c.id
SELECT id, nome, descricao, carga_horaria
FROM curso
WHERE LOWER(nome) LIKE LOWER('%java%')
ORDER BY nome, id;

-- Listar matrículas com o nome do aluno e o nome do curso
-- JPQL: SELECT m FROM Matricula m JOIN FETCH m.aluno JOIN FETCH m.curso
SELECT m.id,
       a.nome AS aluno,
       c.nome AS curso,
       m.data_matricula
FROM matricula m
JOIN aluno a ON a.id = m.aluno_id
JOIN curso c ON c.id = m.curso_id
ORDER BY m.data_matricula DESC, m.id;

