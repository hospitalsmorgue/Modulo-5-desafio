-- ---------------------------------------------------------------------------
-- Tabelas (o mesmo modelo das anotações @Entity)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS aluno (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(120) NOT NULL,
    email           VARCHAR(150) NOT NULL,
    data_nascimento DATE         NOT NULL,
    CONSTRAINT uk_aluno_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS curso (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(120) NOT NULL,
    descricao      VARCHAR(500),
    carga_horaria  INTEGER      NOT NULL
);

CREATE TABLE IF NOT EXISTS matricula (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id       BIGINT NOT NULL,
    curso_id       BIGINT NOT NULL,
    data_matricula DATE   NOT NULL,
    CONSTRAINT uk_matricula_aluno_curso UNIQUE (aluno_id, curso_id),
    CONSTRAINT fk_matricula_aluno FOREIGN KEY (aluno_id) REFERENCES aluno (id),
    CONSTRAINT fk_matricula_curso FOREIGN KEY (curso_id) REFERENCES curso (id)
);

